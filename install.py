#!/usr/bin/env python3
"""Install the mail digest for the current user.

Copies the mail_digest package into ~/.local/share/mail-digest, writes two
launchers into ~/.local/bin, and registers the KRunner desktop entry. Idempotent:
re-run after pulling to update.

Deliberately not pip: Fedora and friends mark the system interpreter as
externally managed (PEP 668), so `pip install --user` fails there without
override flags. Copying a self-contained package avoids the whole argument.
"""
import argparse, os, shutil, subprocess, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
PACKAGE = "mail_digest"
LAUNCHERS = {                       # name in ~/.local/bin -> module to run
    "mail-digest": "mail_digest",
    "mail-digest-gui": "mail_digest.qtui",
}
LAUNCHER_TEMPLATE = """\
#!/usr/bin/env python3
# Generated by install.py -- edits here are overwritten on reinstall.
import runpy, sys

sys.path.insert(0, {libdir!r})
sys.exit(runpy.run_module({module!r}, run_name="__main__"))
"""


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--bindir", type=Path, default=Path.home() / ".local/bin")
    ap.add_argument("--libdir", type=Path,
                    default=Path.home() / ".local/share/mail-digest")
    ap.add_argument("--uninstall", action="store_true")
    args = ap.parse_args()

    apps = Path.home() / ".local/share/applications"
    desktop = apps / "mail-digest.desktop"

    if args.uninstall:
        for name in LAUNCHERS:
            (args.bindir / name).unlink(missing_ok=True)
        shutil.rmtree(args.libdir, ignore_errors=True)
        desktop.unlink(missing_ok=True)
        refresh(apps)
        print("removed launchers, package and desktop entry")
        print("left alone: ~/mail-digest and ~/.local/state/mail-digest")
        return 0

    warn_missing()

    args.libdir.mkdir(parents=True, exist_ok=True)
    args.bindir.mkdir(parents=True, exist_ok=True)
    apps.mkdir(parents=True, exist_ok=True)

    target = args.libdir / PACKAGE
    shutil.rmtree(target, ignore_errors=True)
    shutil.copytree(HERE / PACKAGE, target,
                    ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))

    for name, module in LAUNCHERS.items():
        launcher = args.bindir / name
        launcher.write_text(LAUNCHER_TEMPLATE.format(libdir=str(args.libdir),
                                                     module=module))
        launcher.chmod(0o755)

    desktop.write_text((HERE / "mail-digest.desktop.in").read_text()
                       .replace("@EXEC@", str(args.bindir / "mail-digest-gui")))
    refresh(apps)

    print(f"package -> {target}")
    print(f"launchers -> {', '.join(str(args.bindir / n) for n in LAUNCHERS)}")
    print('launch from KRunner (Alt+Space) as "Mail Digest"')
    if str(args.bindir) not in os.environ.get("PATH", "").split(os.pathsep):
        print(f"note: {args.bindir} is not on your PATH", file=sys.stderr)
    return 0


def warn_missing():
    try:
        import PyQt6  # noqa: F401
    except ImportError:
        print("warning: PyQt6 not importable -- the progress window needs it "
              "(Fedora: sudo dnf install python3-pyqt6)", file=sys.stderr)
    if not shutil.which("claude"):
        print("warning: 'claude' not on PATH -- triage falls back to keyword rules",
              file=sys.stderr)


def refresh(apps):
    for tool in ("kbuildsycoca6", "kbuildsycoca5"):
        if shutil.which(tool):
            subprocess.run([tool, "--noincremental"], check=False,
                           stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    if shutil.which("update-desktop-database"):
        subprocess.run(["update-desktop-database", str(apps)], check=False)


if __name__ == "__main__":
    sys.exit(main())
